import os
import sys
import streamlit as st
from dotenv import load_dotenv
from fastapi import FastAPI, UploadFile, File, Form
from fastapi.middleware.cors import CORSMiddleware
import uvicorn

from helper import load_dataset, get_dataset_overview, LAST_FIG_PATH, set_dataframe
from orchester import ask_agent, get_auto_insights

load_dotenv()

api = FastAPI(title="Autonomous Data Analyst API (Gemini)")
api.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)


@api.get("/")
def health():
    return {"status": "API Running", "llm": "Gemini", "agent": "Autonomous Data Analyst"}


@api.post("/upload")
async def upload_file(file: UploadFile = File(...)):
    df = load_dataset(file.file, filename=file.filename)
    return {"rows": df.shape[0], "columns": df.shape[1], "preview": df.head().to_dict()}


@api.post("/ask")
async def ask_question(question: str = Form(...)):
    context = get_dataset_overview()
    answer = ask_agent(question, context)
    return {"question": question, "answer": answer}


def _maybe_show_chart(response: str):
    if not os.path.exists(LAST_FIG_PATH):
        return
    keys = ["chart", "plot", "graph", "heatmap", "histogram", "scatter", "bar"]
    if any(k in (response or "").lower() for k in keys):
        st.image(LAST_FIG_PATH, caption="Generated by Agent")


def run_streamlit():
    st.set_page_config(page_title="Autonomous Data Analyst", layout="wide", page_icon="📊")
    st.title("Autonomous Data Analyst Agent")
    st.caption("Powered by Gemini + LangGraph + Pandas")
    st.markdown("Upload CSV/Excel. The agent analyzes, visualizes, and explains.")

    if "messages" not in st.session_state:
        st.session_state.messages = []
    if "df" not in st.session_state:
        st.session_state.df = None

    with st.sidebar:
        st.header("Upload Dataset")
        uploaded_file = st.file_uploader("Choose CSV or Excel", type=["csv", "xlsx", "xls"])
        if uploaded_file:
            try:
                df = load_dataset(uploaded_file)
                st.session_state.df = df
                st.success(f"Loaded: {df.shape[0]} rows, {df.shape[1]} cols")
                st.dataframe(df.head(), use_container_width=True)
                with st.expander("Quick Overview"):
                    st.text(get_dataset_overview())
                if st.button("Generate Autonomous Insights"):
                    with st.spinner("Gemini agent is analyzing..."):
                        insights = get_auto_insights()
                        st.session_state.messages.append({"role": "assistant", "content": insights})
            except Exception as e:
                st.error(f"Error: {e}")

        st.divider()
        st.markdown("**Try asking:**")
        st.code(
            "Which category has highest sales?\n"
            "What is average revenue?\n"
            "Show missing values\n"
            "Plot correlation heatmap\n"
            "Bar chart of Sales by Category"
        )

    for msg in st.session_state.messages:
        with st.chat_message(msg["role"]):
            st.markdown(msg["content"])
            if msg["role"] == "assistant":
                _maybe_show_chart(msg["content"])

    if prompt := st.chat_input("Ask about your data..."):
        if st.session_state.df is None:
            st.warning("Please upload a dataset first.")
            return

        set_dataframe(st.session_state.df)
        st.session_state.messages.append({"role": "user", "content": prompt})
        with st.chat_message("user"):
            st.markdown(prompt)

        with st.chat_message("assistant"):
            with st.spinner("Agent is using tools..."):
                context = get_dataset_overview()
                response = ask_agent(prompt, context)
                st.markdown(response)
                _maybe_show_chart(response)
                st.session_state.messages.append({"role": "assistant", "content": response})


if st.runtime.exists():
    # Chal raha hai: streamlit run main.py
    run_streamlit()
elif __name__ == "__main__":
    # Chal raha hai: python main.py -> FastAPI server start karo
    print("=" * 60)
    print("Streamlit UI ke liye ye chalao:")
    print("    streamlit run main.py")
    print("FastAPI server start ho raha hai on http://localhost:8000 ...")
    print("=" * 60)
    uvicorn.run(api, host="0.0.0.0", port=8000)